#!/usr/bin/env node
// Generates lib/database.types.ts from the local database using Supabase's postgres-meta
// (the same generator as `supabase gen types typescript`).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const net = execSync("docker network ls --format '{{.Name}}' | grep powermac-local", { encoding: "utf8" }).trim().split("\n")[0];
try { execSync("docker rm -f pmc-meta", { stdio: "ignore" }); } catch {}
execSync(`docker run -d --name pmc-meta --network ${net} -p 127.0.0.1:54333:8080 -e PG_META_DB_HOST=db -e PG_META_DB_PASSWORD=postgres -e PG_META_DB_USER=postgres -e PG_META_PORT=8080 supabase/postgres-meta:v0.91.0`, { stdio: "ignore" });
let ts = "";
for (let i = 0; i < 30 && !ts; i++) {
  try { ts = execSync("curl -sf 'http://127.0.0.1:54333/generators/typescript?included_schemas=public&detect_one_to_one_relationships=true'", { encoding: "utf8" }); }
  catch { execSync("sleep 1"); }
}
execSync("docker rm -f pmc-meta", { stdio: "ignore" });
if (!ts.includes("export type Database")) throw new Error("type generation failed");
writeFileSync(join(ROOT, "lib/database.types.ts"), "// Generated by scripts/gen-types.mjs from the database schema. Do not edit by hand.\n" + ts);
console.log("wrote lib/database.types.ts", ts.length, "bytes");
